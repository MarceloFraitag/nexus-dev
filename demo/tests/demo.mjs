import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync('src/lib/demo.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {demoRequest:r,demoAnswer}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const base='/api/projects/demo';
const files=await r(base+'/files');assert.equal(files.files.length,4);
const file=await r(base+'/file?path=src/App.tsx');
const changed=file.content+'\n// Edição do teste\n';
await r(base+'/file',{method:'PUT',body:JSON.stringify({path:file.path,content:changed,expected_sha256:file.sha256})});
await assert.rejects(()=>r(base+'/file',{method:'PUT',body:JSON.stringify({path:file.path,content:changed,expected_sha256:file.sha256})}));
assert.equal((await r(base+'/git/status')).changes.length,1);
await r(base+'/git/stage',{body:JSON.stringify({path:file.path})});
assert.equal((await r(base+'/git/status')).changes[0].staged,true);
await r(base+'/git/commit',{body:JSON.stringify({message:'Teste de commit simulado'})});
assert.equal((await r(base+'/git/status')).changes.length,0);
assert.equal((await r(base+'/git/history')).commits.length,2);
const history=await r(base+'/history?path=src/App.tsx');assert.equal(history.revisions.length,1);
await r(base+'/restore',{body:JSON.stringify({path:file.path,revision:history.revisions[0].id})});
assert.equal((await r(base+'/file?path=src/App.tsx')).content,file.content);
assert.equal((await r(base+'/history?path=src/App.tsx')).revisions.length,2);
assert((await r(base+'/search?q=useState')).results.length>0);
assert.match(demoAnswer('bugs'),/demonstrativa/);
await assert.rejects(()=>r('/api/projects/local',{body:'{}'}));
console.log('Demo OK: arquivos, edição, conflito, backup, restauração, busca, stage, commit e identificação da simulação.');
